import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
await MeshoptDecoder.ready;
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.decoder':MeshoptDecoder});
const doc=await io.read('public/models/jining_block_v02.glb');
const payload=JSON.parse(readFileSync('../data/block.json','utf8'));
const expected=new Map(payload.features.filter(x=>x.kind==='building').map(x=>[x.id,x]));
const groupCounts={Architecture:0,Analysis:0,Baseline:0};
let maxHeightError=0,maxPlanBoundsError=0;
const seen=new Map(Object.keys(groupCounts).map(k=>[k,new Set()]));
for(const node of doc.getRoot().listNodes()){
  const extra=node.getExtras();if(!extra.building_id||!groupCounts.hasOwnProperty(extra.category))continue;
  const ref=expected.get(extra.building_id);assert(ref,'Unexpected building ID');assert(!seen.get(extra.category).has(extra.building_id),'Duplicate logical building');
  seen.get(extra.category).add(extra.building_id);groupCounts[extra.category]++;
  const matrix=node.getWorldMatrix();const lo=[Infinity,Infinity,Infinity],hi=[-Infinity,-Infinity,-Infinity];
  for(const primitive of node.getMesh().listPrimitives()){
    const position=primitive.getAttribute('POSITION');
    for(let i=0;i<position.getCount();i++){
      const v=position.getElement(i,[]);
      for(let j=0;j<3;j++){const q=matrix[j]*v[0]+matrix[4+j]*v[1]+matrix[8+j]*v[2]+matrix[12+j];lo[j]=Math.min(lo[j],q);hi[j]=Math.max(hi[j],q);}
    }
  }
  const height=extra.category==='Baseline'?12:ref.height_m;
  maxHeightError=Math.max(maxHeightError,Math.abs(hi[1]-lo[1]-height));
  const points=ref.rings.flat(),x=points.map(p=>p[0]),z=points.map(p=>-p[1]);
  const want=[Math.min(...x),Math.max(...x),Math.min(...z),Math.max(...z)];
  [lo[0],hi[0],lo[2],hi[2]].forEach((v,i)=>maxPlanBoundsError=Math.max(maxPlanBoundsError,Math.abs(v-want[i])));
  if(extra.category==='Architecture')assert(extra.geometry_engine.startsWith('Blosm'),'Blosm engine was not used');
}
for(const [key,count] of Object.entries(groupCounts))assert.equal(count,expected.size,key);
assert(maxHeightError<.05,`Height error ${maxHeightError}`);assert(maxPlanBoundsError<.1,`Footprint bounds error ${maxPlanBoundsError}`);
const result={pass:true,counts:groupCounts,source_buildings:expected.size,max_height_error_m:maxHeightError,max_footprint_bounds_error_m:maxPlanBoundsError,checks:['Meshopt decoded successfully','All building IDs retained in all three views','36 buildings generated by Blosm','Height and plan bounds verified after runtime compression']};
writeFileSync('../output/runtime_validation.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
